-- Кредиты по исходу.
-- Осторожно при интерпретации: A и B — завершённые кредиты, C и D —
-- действующие. Доля дефолтов, посчитанная по всем четырём статусам
-- сразу, смешивает закрытый портфель с открытым и ничего не значит.
select
    case status
        when 'A' then 'A — погашен'
        when 'B' then 'B — закрыт, не погашен'
        when 'C' then 'C — действует, без просрочки'
        when 'D' then 'D — действует, просрочка'
    end as "Статус",
    count(*) as "Кредитов",
    sum(amount) as "Сумма выдачи",
    round(avg(duration)) as "Средний срок, мес"
from berka.loan
group by status
order by status
