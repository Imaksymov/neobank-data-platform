-- Ограничение доступа к персональным данным.
--
-- 004 выдаёт ai_readonly select на все таблицы berka и на все будущие
-- через alter default privileges. Это разумный базовый уровень для
-- операционных данных, но berka.client_pii под него попадать не должен:
-- роль существует для чтения данных ассистентом, а персональные данные
-- в промпты попадать не должны. Запрет на уровне СУБД, а не на уровне
-- договорённости: промпт можно нарушить, grant — нет.
--
-- Порядок важен: этот файл обязан применяться ПОСЛЕ 004, иначе
-- широкий grant перекроет точечный revoke. При инициализации пустого
-- тома порядок обеспечен нумерацией; при ручном применении —
-- на вашей ответственности.

revoke all on berka.client_pii from ai_readonly;

